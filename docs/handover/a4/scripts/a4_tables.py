"""
handover prompt 04 (A4): the memo's tables, from the run's checkpoint alone.

    python -B a4_tables.py CHECKPOINT.jsonl > tables.md

Reads only the checkpoint records (`Run.record` lines); builds no object and runs no cell. Every
cell the run did not compute is printed as its recorded status (`raised` or `skipped`), never as
`not reached`. N = KT_NORM * total / predicted, as A2's `N_of`; the representation term of a cell
is N_arm - N_E at the same rung, beside both cells' declared errors converted to N (A2's `term`).
After landing, this file is a record of its own SHA-256.
"""

import json
import sys
from collections import OrderedDict

KT_NORM = (
    -9.0 / 8.0
)  # ComputeTargets.tests.kohri_terada.KT_NORM, checked below against N + 9/8

LADDER = OrderedDict(
    [
        ("together", (980.0, 1e4, 1e5, 1e6, 1e7, 1e8)),
        ("T-first", (980.0, 1e4, 1e5, 1e6, 1e7)),
        ("q-smooth", (980.0, 1e4, 1e5, 1e6)),
    ]
)
ARMS = ("E", "S", "P0", "P")

# A2's Table 8 (docs/handover/REALISTIC-LARGE-X.md), pre-B1: exact and realistic (closed seam)
A2 = {
    "together": {
        980.0: (7, 1304, 18.5),
        1e4: (8, 12068, 173.4),
        1e5: (8, 27253, 410.2),
        1e6: (9, 20253, 299.2),
        1e7: (9, 50463, 773.7),
        1e8: (9, 15827, 241.9),
    },
    "T-first": {
        980.0: (7, 720, 7.2),
        1e4: (10, 3444, 48.1),
        1e5: (9, 19375, 310.7),
        1e6: (12, 36728, 576.0),
        1e7: (13, 75570, 1229.8),
    },
    "q-smooth": {
        980.0: (17, 855, 6.8),
        1e4: (21, 5018, 62.4),
        1e5: (21, 31358, 514.8),
        1e6: (16, None, None),
    },
}


def load(path):
    cells = {}
    for line in open(path):
        line = line.strip()
        if not line:
            continue
        rec = json.loads(line)
        d = rec["data"]
        d["_script_sha256"] = rec.get("script_sha256")
        d["_git_head"] = rec.get("git_head")
        d["_git_dirty"] = rec.get("git_dirty")
        cells[(d["arm"], d["shape"], float(d["x_resp"]))] = d
    return cells


def N(cell):
    return KT_NORM * cell["total"] / cell["ref"]["predicted"]


def st(cell):
    return "missing" if cell is None else cell["status"]


def main():
    cells = load(sys.argv[1])
    for c in cells.values():
        if c["status"] == "ok":
            assert abs((N(c) - KT_NORM) - c["N_plus_9_8"]) <= 1e-12 * max(
                1.0, abs(c["N_plus_9_8"])
            ), c["unit"]
    print("<!-- generated by a4_tables.py from the run's checkpoint -->\n")

    # provenance
    shas = {c.get("_script_sha256") for c in cells.values()}
    heads = {c.get("_git_head") for c in cells.values()}
    dirty = {c.get("_git_dirty") for c in cells.values()}
    cell_shas = {
        c.get("a4_cells_sha256") for c in cells.values() if "a4_cells_sha256" in c
    }
    status_short = {c.get("tree_status_short", "").strip() for c in cells.values()}
    tree_heads = {c.get("tree_head") for c in cells.values()}
    print(
        f"**Provenance.** {len(cells)} records; driver SHA-256 {sorted(shas)}; a4_cells SHA-256 "
        f"{sorted(cell_shas)}; launch git_head {sorted(heads)}, dirty {sorted(dirty)}; per-cell "
        f"tree_head {sorted(tree_heads)}; per-cell `git status --short` "
        f"{sorted(status_short)!r}.\n"
    )
    counts = {}
    for c in cells.values():
        counts[c["status"]] = counts.get(c["status"], 0) + 1
    print(f"**Statuses.** {counts}\n")

    # Table A: regions and max depth per cell and arm
    print("**Table A -- Levin regions / maximum depth, per cell and arm.**\n")
    print("| shape | x_resp | x = k tau | E | S | P0 | P |")
    print("|---|---|---|---|---|---|---|")
    for shape, rungs in LADDER.items():
        for x in rungs:
            ref = next(
                (
                    cells[(a, shape, x)]["ref"]
                    for a in ARMS
                    if st(cells.get((a, shape, x))) == "ok"
                ),
                None,
            )
            row = [shape, f"{x:g}", f"{ref['x']:.4e}" if ref else "--"]
            for a in ARMS:
                c = cells.get((a, shape, x))
                row.append(
                    f"{c['Levin_regions']} / {c['max_depth']}"
                    if st(c) == "ok"
                    else f"**{st(c)}**"
                )
            print("| " + " | ".join(row) + " |")
    print()

    # Table B: growth per shape and arm
    print(
        "**Table B -- growth across the ladder:** regions at the highest rung reached over regions "
        "at 980, per shape and arm (prompt 04 section 4's measure). `rungs` is the rungs the arm "
        "has `ok` on that shape.\n"
    )
    print(
        "| shape | arm | rungs ok | regions at 980 | highest rung ok | regions there | growth |"
    )
    print("|---|---|---|---|---|---|---|")
    for shape, rungs in LADDER.items():
        for a in ARMS:
            ok = [x for x in rungs if st(cells.get((a, shape, x))) == "ok"]
            base = cells.get((a, shape, 980.0))
            if not ok or st(base) != "ok":
                print(
                    f"| {shape} | {a} | {len(ok)} of {len(rungs)} | "
                    f"{'**' + st(base) + '**' if st(base) != 'ok' else base['Levin_regions']} "
                    f"| -- | -- | -- |"
                )
                continue
            top = cells[(a, shape, ok[-1])]
            g = top["Levin_regions"] / base["Levin_regions"]
            print(
                f"| {shape} | {a} | {len(ok)} of {len(rungs)} | {base['Levin_regions']} | "
                f"{ok[-1]:g} | {top['Levin_regions']} | {g:.3g} |"
            )
    print()

    # Table K: the attribution, as ratios of growths (run 2 addition)
    def growth(a, shape):
        rungs = LADDER[shape]
        ok = [x for x in rungs if st(cells.get((a, shape, x))) == "ok"]
        if len(ok) != len(rungs):
            return None, None
        top = cells[(a, shape, rungs[-1])]
        return (
            top["Levin_regions"] / cells[(a, shape, rungs[0])]["Levin_regions"],
            top,
        )

    print(
        "**Table K -- the attribution, as ratios of growths** (prompt 04 section 4): growth is "
        "regions at the top rung over regions at 980, on shapes where the arm has every rung. "
        "`S/P0` is S's growth over P0's (what the `phase_spline` floor adds, against P0); `P0/P` "
        "is P0's over P's (what the anchoring floor adds). `carrier` is the group carrying the "
        "maximum depth at the top rung (Levin sub-interval : regime : group), with that depth.\n"
    )
    print(
        "| shape | top rung | growth E | growth S | growth P0 | growth P | S/P0 | P0/P | "
        "P/E | carrier S | carrier P0 | carrier P |"
    )
    print("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for shape, rungs in LADDER.items():
        g = {a: growth(a, shape) for a in ARMS}
        if any(v[0] is None for v in g.values()):
            print(f"| {shape} | {rungs[-1]:g} | " + " | ".join(["--"] * 10) + " |")
            continue

        def carrier(a):
            c = g[a][1]
            m = c["max_depth_group"]
            return f"{m['subinterval']}:{m['regime']}:{m['label']} (depth {c['max_depth']})"

        print(
            f"| {shape} | {rungs[-1]:g} | {g['E'][0]:.3g} | {g['S'][0]:.3g} | "
            f"{g['P0'][0]:.3g} | {g['P'][0]:.3g} | {g['S'][0] / g['P0'][0]:.3g} | "
            f"{g['P0'][0] / g['P'][0]:.3g} | {g['P'][0] / g['E'][0]:.3g} | {carrier('S')} | "
            f"{carrier('P0')} | {carrier('P')} |"
        )
    print()

    # Table C: level at 980
    print("**Table C -- the level at 980:** regions per arm over arm E's.\n")
    print("| shape | E | S | S/E | P0 | P0/E | P | P/E |")
    print("|---|---|---|---|---|---|---|---|")
    for shape in LADDER:
        e = cells.get(("E", shape, 980.0))
        row = [shape, str(e["Levin_regions"]) if st(e) == "ok" else st(e)]
        for a in ("S", "P0", "P"):
            c = cells.get((a, shape, 980.0))
            if st(c) == "ok" and st(e) == "ok":
                row += [
                    str(c["Levin_regions"]),
                    f"{c['Levin_regions'] / e['Levin_regions']:.3g}",
                ]
            else:
                row += [f"**{st(c)}**", "--"]
        print("| " + " | ".join(row) + " |")
    print()

    # Table D: time and load
    print(
        "**Table D -- `integral_time` (s) with the 1-minute load average at the cell's start and "
        "end.** Up to four cells ran at once; times are indicative only.\n"
    )
    print(
        "| shape | x_resp | arm | integral_time | setup_time | load start | load end |"
    )
    print("|---|---|---|---|---|---|---|")
    for shape, rungs in LADDER.items():
        for x in rungs:
            for a in ARMS:
                c = cells.get((a, shape, x))
                if st(c) != "ok":
                    print(f"| {shape} | {x:g} | {a} | **{st(c)}** | -- | -- | -- |")
                    continue
                print(
                    f"| {shape} | {x:g} | {a} | {c['integral_time']:.2f} | {c['setup_time']:.3f} "
                    f"| {c['loadavg_before'][0]:.2f} | {c['loadavg_after'][0]:.2f} |"
                )
    print()

    # Table E: cells not computed
    print(
        "**Table E -- cells not computed.** None is `not reached`: no cell hit its budget.\n"
    )
    print("| cell | status | reason |")
    print("|---|---|---|")
    for key, c in cells.items():
        if c["status"] != "ok":
            print(f"| {c['unit']} | {c['status']} | {c.get('error', '')} |")
    print()

    # Table F: A2's curves, pre-B1
    print(
        "**Table F -- A2's recorded curves, pre-B1, context only** (`REALISTIC-LARGE-X.md` "
        "Table 8: exact and realistic regions, closed seam, realistic integral seconds on the "
        "laptop), beside this run's E and S regions.\n"
    )
    print("| shape | x_resp | A2 exact | A2 realistic | A2 realistic s | A4 E | A4 S |")
    print("|---|---|---|---|---|---|---|")
    for shape, rungs in LADDER.items():
        for x in rungs:
            ex, re, t = A2[shape][x]
            e, s = cells.get(("E", shape, x)), cells.get(("S", shape, x))
            print(
                f"| {shape} | {x:g} | {ex} | {re if re is not None else 'not reached'} | "
                f"{t if t is not None else '--'} | "
                f"{e['Levin_regions'] if st(e) == 'ok' else st(e)} | "
                f"{s['Levin_regions'] if st(s) == 'ok' else st(s)} |"
            )
    print()

    # Table G: depth record
    print(
        "**Table G -- the depth record:** per cell, the group carrying the maximum depth (Levin "
        "sub-interval index : regime : group), its z-range of deepest regions, every group at "
        "that depth, and the phase-limited region count.\n"
    )
    print(
        "| shape | x_resp | arm | max depth | carrier | its regions | deepest regions | "
        "their z' range | all groups at max depth | phase-limited regions |"
    )
    print("|---|---|---|---|---|---|---|---|---|---|")
    for shape, rungs in LADDER.items():
        for a in ARMS:
            for x in rungs:
                c = cells.get((a, shape, x))
                if st(c) != "ok":
                    continue
                g = c["max_depth_group"]
                print(
                    f"| {shape} | {x:g} | {a} | {c['max_depth']} | "
                    f"{g['subinterval']}:{g['regime']}:{g['label']} | {g['num_regions']} | "
                    f"{g['deepest_count']} | {g['deepest_z'][0]:.6g} - {g['deepest_z'][1]:.6g} | "
                    f"{', '.join(c['groups_at_max_depth'])} | {c['phase_limited_regions']} |"
                )
    print()

    # Table H: representation term
    print(
        "**Table H -- the representation term, recorded, no verdict:** N_arm - N_E at the same "
        "rung, both scored against the same 50-digit reference; `+/-` is the sum of the two "
        "cells' declared errors converted to N (A2's `term`).\n"
    )
    print(
        "| shape | x_resp | N_E + 9/8 | E declared | arm | N_arm + 9/8 | arm declared | "
        "N_arm - N_E | +/- |"
    )
    print("|---|---|---|---|---|---|---|---|---|")
    for shape, rungs in LADDER.items():
        for x in rungs:
            e = cells.get(("E", shape, x))
            for a in ("S", "P0", "P"):
                c = cells.get((a, shape, x))
                if st(c) != "ok" or st(e) != "ok":
                    print(
                        f"| {shape} | {x:g} | "
                        f"{e['N_plus_9_8']:+.3e} | {e['declared']:.1e} | {a} | **{st(c)}** | -- | -- | -- |"
                        if st(e) == "ok"
                        else f"| {shape} | {x:g} | -- | -- | {a} | **{st(c)}** | -- | -- | -- |"
                    )
                    continue
                d = N(c) - N(e)
                err = abs(N(c)) * c["declared"] + abs(N(e)) * e["declared"]
                print(
                    f"| {shape} | {x:g} | {e['N_plus_9_8']:+.3e} | {e['declared']:.1e} | {a} | "
                    f"{c['N_plus_9_8']:+.3e} | {c['declared']:.1e} | {d:+.3e} | {err:.1e} |"
                )
    print()

    # Table I: T anchors
    print(
        "**Table I -- the realistic T anchors:** p_R per fixture (z_init off a node).\n"
    )
    print(
        "| shape | x_resp | p_R, T_q | p_R, T_r | anchor node, T_q | anchor node, T_r |"
    )
    print("|---|---|---|---|---|---|")
    for shape, rungs in LADDER.items():
        for x in rungs:
            c = next(
                (
                    cells[(a, shape, x)]
                    for a in ("S", "P0", "P")
                    if st(cells.get((a, shape, x))) == "ok"
                ),
                None,
            )
            if c is None:
                continue
            po = c["phase_objects"]
            print(
                f"| {shape} | {x:g} | {po['Tq']['p_R']:+.4e} | {po['Tr']['p_R']:+.4e} | "
                f"{po['Tq']['anchor_node_index']} | {po['Tr']['anchor_node_index']} |"
            )
    print()

    # phase objects per arm, summarised
    print(
        "**Phase objects, as every `ok` cell records them** (class / exact_remainder):\n"
    )
    seen = {}
    for c in cells.values():
        if c["status"] != "ok":
            continue
        po = c["phase_objects"]
        key = (
            c["arm"],
            f"G {po['G']['class']}/{po['G']['exact_remainder']}",
            f"Tq {po['Tq']['class']}/{po['Tq']['exact_remainder']}/{po['Tq'].get('leading_class')}",
            f"Tr {po['Tr']['class']}/{po['Tr']['exact_remainder']}/{po['Tr'].get('leading_class')}",
            f"construction_ok {c['construction_ok']}",
        )
        seen[key] = seen.get(key, 0) + 1
    for key, n in sorted(seen.items()):
        print(f"- {key[0]}: {', '.join(key[1:])} -- {n} cells")


if __name__ == "__main__":
    main()
