"""Fill POLICY-GEOMETRY.template.md from the census's stdout (read-only on out/, writes the document).

    ./venv/bin/python -I var/handover-03/scripts/assemble_doc.py

Blocks: {{block:NAME}} is the text between `<!-- section:NAME -->` and `<!-- end:NAME -->` in the census's stdout;
{{sec:N}} is the body of its `## N. ...` section, with the section's own markers removed; {{answer}} is answer.md;
{{sha}} is the script SHA-256 from the census header.
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
out = open(os.path.join(ROOT, "out", "policy_geometry_03.txt")).read()
tpl = open(os.path.join(HERE, "POLICY-GEOMETRY.template.md")).read()
sha = re.search(r"^script sha256\s+(\w+)", out, re.M).group(1)
MARK = (
    "<!-- generated by var/handover-03/scripts/policy_geometry.py (SHA-256 %s), %s -->\n"
    % (sha, "%s")
)


def block(name):
    m = re.search(
        r"<!-- section:%s -->\n(.*?)<!-- end:%s -->"
        % (re.escape(name), re.escape(name)),
        out,
        re.S,
    )
    assert m, name
    return (MARK % ("block " + name)) + m.group(1).rstrip("\n") + "\n"


def sec(n):
    m = re.search(r"^## %s\. .*?\n(.*?)(?=^## |\Z)" % n, out, re.S | re.M)
    assert m, n
    body = re.sub(r"<!-- (section|end):\w+ -->\n", "", m.group(1)).strip("\n")
    return (MARK % ("script section %s" % n)) + body + "\n"


def sub(m):
    kind, name = m.group(1), m.group(2)
    if kind == "block":
        return block(name)
    if kind == "sec":
        return sec(name)
    raise KeyError(m.group(0))


doc = tpl.replace(
    "{{answer}}", open(os.path.join(HERE, "answer.md")).read().rstrip("\n")
)
doc = doc.replace("{{sha}}", sha)
doc = re.sub(r"\{\{(block|sec):(\w+)\}\}", sub, doc)
assert "{{" not in doc
open(os.path.join(ROOT, "POLICY-GEOMETRY.md"), "w").write(doc)
print("wrote", os.path.join(ROOT, "POLICY-GEOMETRY.md"), len(doc), "bytes")
