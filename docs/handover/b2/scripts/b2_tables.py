"""
handover prompt 13 (B2), Part B: SEAM-RESIDUE.md's section 3 tables, from the run's checkpoint
alone.

    python -B b2_tables.py CHECKPOINT.jsonl > tables.md

Reads only the checkpoint records (`Run.record` lines); builds no object and runs no cell. Every
cell the run did not compute is printed as its recorded status (`not reached`, `raised` or
`skipped`).

N = KT_NORM * total / predicted, as A2's `N_of`; a difference of two cells' N carries the sum of
their declared errors converted to N, |N| * declared (A2's `term`). The 50-digit reference is
common to every cell of a rung and cancels in every difference, so it adds nothing to those
errors (A2 section 0). Per rung (prompt 13 section 2.3):

    D      = N_R - N_E'                    the residue
    A_i    = N_E'+i - N_E'                 add-one
    B_i    = N_R - N_R-i                   remove-one
    sum_i A_i - D, sum_i B_i - D           the interactions
    N_E' - N_E                             the geometry control

**Additivity rule (fixed in state/terms.md before the launch):** a rung where
|sum_i A_i - D| or |sum_i B_i - D| exceeds the largest |A_i| is reported **not additive at that
rung**, and no per-term attribution is given there without saying so. No threshold beyond that.

The tables script is not part of the run's hashed set (the run's records hash the cell, driver,
checks and launcher scripts); it is a record of its own SHA-256 once landed.
"""

import json
import sys
from collections import OrderedDict

KT_NORM = -9.0 / 8.0  # ComputeTargets.tests.kohri_terada.KT_NORM
TERMS = ("f", "Tnum", "Trep", "TLG", "G")
OBJECTS = ("E", "R", "Ep") + tuple(f"Ep+{t}" for t in TERMS) + tuple(f"R-{t}" for t in TERMS)
LADDER = OrderedDict(
    [
        ("together", (980.0, 1e4, 1e5, 1e6, 1e7, 1e8)),
        ("T-first", (980.0, 1e4, 1e5, 1e6, 1e7)),
        ("q-smooth", (980.0, 1e4, 1e5, 1e6, 1e7)),
    ]
)
LABEL = {"Ep": "E'"} | {f"Ep+{t}": f"E'+{t}" for t in TERMS}


def load(path):
    cells = {}
    for line in open(path):
        line = line.strip()
        if not line:
            continue
        rec = json.loads(line)
        d = rec["data"]
        d["_script_sha256"] = rec.get("script_sha256")
        d["_git_head"] = rec.get("git_head")
        cells[(d["object"], d["shape"], float(d["x_resp"]))] = d
    return cells


def ok(cell):
    return cell is not None and cell.get("status") == "ok"


def N(cell):
    return KT_NORM * cell["total"] / cell["ref"]["predicted"]


def eN(cell):
    return abs(N(cell)) * cell["declared"]


def diff(a, b):
    if not (ok(a) and ok(b)):
        return None, None
    return N(a) - N(b), eN(a) + eN(b)


def slope(xs, ys):
    """Least-squares slope of log|y| against log x (A2's `slope`)."""
    from math import log

    pairs = [(log(a), log(abs(b))) for a, b in zip(xs, ys) if b not in (None, 0.0)]
    if len(pairs) < 2:
        return None
    mx = sum(p[0] for p in pairs) / len(pairs)
    my = sum(p[1] for p in pairs) / len(pairs)
    num = sum((p[0] - mx) * (p[1] - my) for p in pairs)
    den = sum((p[0] - mx) ** 2 for p in pairs)
    return num / den if den else None


def fmt(v, spec="+.3e"):
    return "--" if v is None else format(v, spec)


def st(cell):
    return "missing" if cell is None else cell["status"]


def main():
    cells = load(sys.argv[1])
    print("<!-- generated by docs/handover/b2/scripts/b2_tables.py from the run's checkpoint -->\n")

    # Table 1: N + 9/8 per object and cell
    print("**Table 1 -- N + 9/8 per object and rung**, with each cell's declared error in N "
          "(and, for E and R, the reference's own: eq. (22) and the head at 50 digits, "
          "negligible against these).\n")
    print("| shape | x_resp | " + " | ".join(LABEL.get(o, o) for o in OBJECTS) + " |")
    print("|---|---|" + "---|" * len(OBJECTS))
    for shape, rungs in LADDER.items():
        for x in rungs:
            row = []
            for o in OBJECTS:
                c = cells.get((o, shape, x))
                row.append(
                    f"{N(c) - KT_NORM:+.4e} ({eN(c):.0e})" if ok(c) else st(c)
                )
            print(f"| {shape} | {x:g} | " + " | ".join(row) + " |")

    # Table 2: D, A_i, B_i, interactions, geometry control
    print("\n**Table 2 -- the residue and its terms per rung**, each with the sum of the cells' "
          "declared errors in N.\n")
    head = ["D = N_R - N_E'"] + [f"A_{t}" for t in TERMS] + ["sum A - D"] + [
        f"B_{t}" for t in TERMS
    ] + ["sum B - D", "additive?", "N_E' - N_E"]
    print("| shape | x_resp | " + " | ".join(head) + " |")
    print("|---|---|" + "---|" * len(head))
    summary = []
    for shape, rungs in LADDER.items():
        for x in rungs:
            g = lambda o: cells.get((o, shape, x))  # noqa: E731
            D, eD = diff(g("R"), g("Ep"))
            A = {t: diff(g(f"Ep+{t}"), g("Ep")) for t in TERMS}
            B = {t: diff(g("R"), g(f"R-{t}")) for t in TERMS}
            geo = diff(g("Ep"), g("E"))
            cols = [f"{fmt(D)} ({fmt(eD, '.0e')})"]
            cols += [f"{fmt(A[t][0])} ({fmt(A[t][1], '.0e')})" for t in TERMS]
            if D is not None and all(A[t][0] is not None for t in TERMS):
                IA = sum(A[t][0] for t in TERMS) - D
                eIA = sum(A[t][1] for t in TERMS) + eD
            else:
                IA = eIA = None
            cols.append(f"{fmt(IA)} ({fmt(eIA, '.0e')})")
            cols += [f"{fmt(B[t][0])} ({fmt(B[t][1], '.0e')})" for t in TERMS]
            if D is not None and all(B[t][0] is not None for t in TERMS):
                IB = sum(B[t][0] for t in TERMS) - D
                eIB = sum(B[t][1] for t in TERMS) + eD
            else:
                IB = eIB = None
            cols.append(f"{fmt(IB)} ({fmt(eIB, '.0e')})")
            if IA is None or IB is None:
                additive = "--"
            else:
                largest = max(abs(A[t][0]) for t in TERMS)
                additive = "yes" if max(abs(IA), abs(IB)) <= largest else "**not additive**"
            cols.append(additive)
            cols.append(f"{fmt(geo[0])} ({fmt(geo[1], '.0e')})")
            print(f"| {shape} | {x:g} | " + " | ".join(cols) + " |")
            summary.append((shape, x, D, A, B, IA, IB, additive))

    # Table 3: cells not computed
    print("\n**Table 3 -- the cells not computed** (`not reached`: killed over the 1 h budget, with "
          "its elapsed time; `raised` and `skipped` with the recorded reason).\n")
    print("| shape | x_resp | object | status | elapsed / reason |")
    print("|---|---|---|---|---|")
    n = 0
    for shape, rungs in LADDER.items():
        for x in rungs:
            for o in OBJECTS:
                c = cells.get((o, shape, x))
                if not ok(c):
                    n += 1
                    why = "" if c is None else (
                        f"{c.get('elapsed_s', 0.0):.0f} s" if c.get("status") == "not reached"
                        else c.get("error", "")
                    )
                    print(f"| {shape} | {x:g} | {LABEL.get(o, o)} | {st(c)} | {why} |")
    if n == 0:
        print("| -- | -- | -- | none | -- |")

    # Table 4: cost, R
    print("\n**Table 4 -- cost of R per rung**, recorded without a reading: Levin regions, maximum "
          "depth, integral time and the 1-minute load at the cell's start.\n")
    print("| shape | x_resp | Levin regions | max depth | integral_time | load |")
    print("|---|---|---|---|---|---|")
    for shape, rungs in LADDER.items():
        for x in rungs:
            c = cells.get(("R", shape, x))
            if ok(c):
                print(f"| {shape} | {x:g} | {c['Levin_regions']} | {c['max_depth']} | "
                      f"{c['integral_time']:.2f} s | {c['loadavg_before'][0]:.1f} |")
            else:
                print(f"| {shape} | {x:g} | {st(c)} | | | |")

    # Table 5: per shape and term, range, sign and x_resp scaling
    print("\n**Table 5 -- each term per shape over the ladder**: the range of A_i (and of D), "
          "its signs, the largest |A_i| / |D| over the rungs, and a least-squares slope of "
          "log|A_i| against log x_resp where |A_i| is monotone in x_resp (A2's Table 4 "
          "convention); '--' where it is not.\n")
    print("| shape | quantity | min | max | signs | max over rungs of abs(A_i)/abs(D) | monotone? | slope |")
    print("|---|---|---|---|---|---|---|---|")
    for shape, rungs in LADDER.items():
        series = {"D": []} | {t: [] for t in TERMS}
        xs = []
        for (sh, x, D, A, B, IA, IB, additive) in summary:
            if sh != shape or D is None:
                continue
            xs.append(x)
            series["D"].append(D)
            for t in TERMS:
                series[t].append(A[t][0])
        for name, ys in series.items():
            if not ys:
                continue
            a = [abs(y) for y in ys]
            inc = all(a[i] < a[i + 1] for i in range(len(a) - 1))
            dec = all(a[i] > a[i + 1] for i in range(len(a) - 1))
            mono = "increasing" if inc else ("decreasing" if dec else "no")
            sl = slope(xs, ys) if mono != "no" else None
            signs = "".join("+" if y > 0 else ("-" if y < 0 else "0") for y in ys)
            ratio = "" if name == "D" else f"{max(abs(y) / abs(d) for y, d in zip(ys, series['D'])):.3g}"
            label = "D" if name == "D" else f"A_{name}"
            print(f"| {shape} | {label} | {min(ys):+.3e} | {max(ys):+.3e} | {signs} | {ratio} | "
                  f"{mono} | {fmt(sl, '+.2f')} |")

    # Table 6: interactions against the largest single term
    print("\n**Table 6 -- the interactions against the additivity rule** (the rule: not additive "
          "where max(abs(sum A - D), abs(sum B - D)) > max_i abs(A_i)).\n")
    print("| shape | x_resp | abs(sum A - D) | abs(sum B - D) | max_i abs(A_i) | ratio | verdict |")
    print("|---|---|---|---|---|---|---|")
    for (sh, x, D, A, B, IA, IB, additive) in summary:
        if IA is None or IB is None:
            print(f"| {sh} | {x:g} | -- | -- | -- | -- | {additive} |")
            continue
        largest = max(abs(A[t][0]) for t in TERMS)
        r = max(abs(IA), abs(IB)) / largest
        print(f"| {sh} | {x:g} | {abs(IA):.3e} | {abs(IB):.3e} | {largest:.3e} | {r:.3f} | {additive} |")

    heads = {c.get("_git_head") for c in cells.values()}
    shas = {c.get("_script_sha256") for c in cells.values()}
    print(f"\n{len(cells)} records; git_head {sorted(h for h in heads if h)}; driver sha256 "
          f"{sorted(s for s in shas if s)}")


if __name__ == "__main__":
    main()
